-- Ejecutar como propietario de las tablas después de add_stock_movements.sql.
-- Los borradores no modifican stock. Controlar registra ingreso e historial en una transacción.
BEGIN;
CREATE TABLE IF NOT EXISTS empresa_configuracion (
 id_empresa integer PRIMARY KEY REFERENCES empresas(id_empresa), direccion varchar(300) NOT NULL DEFAULT '',
 web varchar(200) NOT NULL DEFAULT '', facturacion jsonb NOT NULL DEFAULT '{}', version integer NOT NULL DEFAULT 1,
 id_usuario_modificacion integer NOT NULL REFERENCES usuarios(id_usuario), fecha_modificacion timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS proveedores (
 id_proveedor integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_empresa integer NOT NULL REFERENCES empresas(id_empresa),
 nombre varchar(200) NOT NULL, cuit varchar(11), condicion_iva varchar(80) NOT NULL DEFAULT '', contacto varchar(150) NOT NULL DEFAULT '',
 telefono varchar(60) NOT NULL DEFAULT '', email varchar(200) NOT NULL DEFAULT '', direccion varchar(300) NOT NULL DEFAULT '',
 observaciones varchar(1000) NOT NULL DEFAULT '', activo boolean NOT NULL DEFAULT true, version integer NOT NULL DEFAULT 1,
 CHECK(cuit IS NULL OR cuit ~ '^[0-9]{11}$')
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_proveedores_cuit ON proveedores(id_empresa,cuit) WHERE cuit IS NOT NULL;
CREATE TABLE IF NOT EXISTS proveedor_productos (
 id_proveedor integer NOT NULL REFERENCES proveedores(id_proveedor), id_producto integer NOT NULL REFERENCES productos(id_producto),
 codigo_proveedor varchar(80) NOT NULL DEFAULT '', PRIMARY KEY(id_proveedor,id_producto)
);
CREATE TABLE IF NOT EXISTS compras (
 id_compra integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_empresa integer NOT NULL REFERENCES empresas(id_empresa), id_sucursal integer NOT NULL REFERENCES sucursales(id_sucursal),
 id_proveedor integer NOT NULL REFERENCES proveedores(id_proveedor), proveedor_nombre varchar(200) NOT NULL,
 tipo_comprobante varchar(20) NOT NULL CHECK(tipo_comprobante IN ('Factura','Remito')), letra varchar(1) NOT NULL DEFAULT '',
 punto_venta integer NOT NULL DEFAULT 0 CHECK(punto_venta BETWEEN 0 AND 99999), numero varchar(30) NOT NULL,
 fecha_comprobante date NOT NULL, total_comprobante numeric(15,2) CHECK(total_comprobante>=0), observaciones varchar(1000) NOT NULL DEFAULT '',
 estado varchar(20) NOT NULL DEFAULT 'Borrador' CHECK(estado IN ('Borrador','Controlado','Anulado')), version integer NOT NULL DEFAULT 1,
 id_usuario_carga integer NOT NULL REFERENCES usuarios(id_usuario), usuario_carga text NOT NULL, fecha_carga timestamptz NOT NULL,
 id_usuario_control integer REFERENCES usuarios(id_usuario), usuario_control text, fecha_control timestamptz,
 clave_solicitud varchar(64) NOT NULL, UNIQUE(id_empresa,clave_solicitud),
 CHECK((estado='Controlado') = (id_usuario_control IS NOT NULL AND fecha_control IS NOT NULL)),
 CHECK(tipo_comprobante <> 'Factura' OR (letra IN ('A','B','C','M','E') AND punto_venta>0))
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_compras_comprobante ON compras(id_empresa,id_proveedor,tipo_comprobante,letra,punto_venta,numero) WHERE estado<>'Anulado';
CREATE INDEX IF NOT EXISTS ix_compras_sucursal ON compras(id_empresa,id_sucursal,id_compra DESC);
CREATE TABLE IF NOT EXISTS compra_items (
 id_compra integer NOT NULL REFERENCES compras(id_compra), id_producto integer NOT NULL REFERENCES productos(id_producto),
 producto_nombre text NOT NULL, cantidad numeric(15,3) NOT NULL CHECK(cantidad>0), costo_unitario numeric(15,2) NOT NULL CHECK(costo_unitario>=0),
 PRIMARY KEY(id_compra,id_producto)
);
CREATE TABLE IF NOT EXISTS compra_historial (
 id_evento bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, id_compra integer NOT NULL REFERENCES compras(id_compra),
 id_usuario integer NOT NULL REFERENCES usuarios(id_usuario), usuario text NOT NULL, fecha timestamptz NOT NULL,
 accion text NOT NULL, motivo varchar(1000) NOT NULL DEFAULT '', datos jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_compra_historial_compra ON compra_historial(id_compra,id_evento);
ALTER TABLE movimientos_stock DROP CONSTRAINT IF EXISTS movimientos_stock_origen_check;
ALTER TABLE movimientos_stock ADD CONSTRAINT movimientos_stock_origen_check CHECK(origen IN ('Manual','Venta','Compuesto','Compra'));
CREATE UNIQUE INDEX IF NOT EXISTS ux_movimientos_stock_compra ON movimientos_stock(id_referencia,id_producto) WHERE origen='Compra';
DO $$ BEGIN
 IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='foco_api') THEN
  GRANT SELECT,INSERT,UPDATE ON empresa_configuracion,proveedores,compras TO foco_api;
  GRANT SELECT,INSERT,UPDATE,DELETE ON proveedor_productos,compra_items TO foco_api;
  GRANT SELECT,INSERT ON compra_historial TO foco_api;
  REVOKE UPDATE,DELETE,TRUNCATE ON compra_historial FROM foco_api;
  GRANT USAGE,SELECT ON SEQUENCE proveedores_id_proveedor_seq,compras_id_compra_seq,compra_historial_id_evento_seq TO foco_api;
 END IF;
END $$;
COMMIT;
