-- Facturación electrónica AFIP/ARCA (WSAA + WSFEv1).
-- Ejecutar como propietario de las tablas después de add_company_purchases.sql.
-- Transaccional y repetible. No factura ventas existentes.
BEGIN;

-- Clave privada (cifrada por la API), pedido de certificado y certificado por ambiente.
CREATE TABLE IF NOT EXISTS afip_credenciales (
 id_empresa integer NOT NULL REFERENCES empresas(id_empresa),
 ambiente varchar(20) NOT NULL CHECK(ambiente IN ('Homologacion','Produccion')),
 clave_privada bytea NOT NULL, csr text NOT NULL, certificado text,
 certificado_sujeto text, certificado_vence timestamptz,
 fecha_creacion timestamptz NOT NULL, fecha_certificado timestamptz,
 PRIMARY KEY(id_empresa, ambiente)
);

-- Ticket de acceso de WSAA: AFIP no entrega otro mientras el vigente no venza.
CREATE TABLE IF NOT EXISTS afip_tokens (
 id_empresa integer NOT NULL REFERENCES empresas(id_empresa),
 ambiente varchar(20) NOT NULL, servicio varchar(30) NOT NULL,
 token text NOT NULL, sign text NOT NULL, vence timestamptz NOT NULL,
 PRIMARY KEY(id_empresa, ambiente, servicio)
);

CREATE TABLE IF NOT EXISTS comprobantes (
 id_comprobante integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_empresa integer NOT NULL REFERENCES empresas(id_empresa),
 id_sucursal integer NOT NULL REFERENCES sucursales(id_sucursal),
 id_venta integer NOT NULL REFERENCES ventas(id_venta),
 ambiente varchar(20) NOT NULL CHECK(ambiente IN ('Homologacion','Produccion')),
 tipo_comprobante integer NOT NULL, punto_venta integer NOT NULL CHECK(punto_venta BETWEEN 1 AND 99999),
 numero bigint NOT NULL, fecha date NOT NULL, concepto integer NOT NULL,
 doc_tipo integer NOT NULL, doc_nro bigint NOT NULL, receptor_nombre varchar(200) NOT NULL DEFAULT '',
 receptor_condicion_iva integer NOT NULL, id_cliente integer REFERENCES clientes(id_cliente),
 imp_total numeric(15,2) NOT NULL, imp_neto numeric(15,2) NOT NULL, imp_iva numeric(15,2) NOT NULL,
 iva jsonb NOT NULL DEFAULT '[]',
 estado varchar(20) NOT NULL CHECK(estado IN ('Procesando','Autorizado','Rechazado')),
 cae varchar(20), cae_vence date, mensajes text NOT NULL DEFAULT '',
 id_comprobante_asociado integer REFERENCES comprobantes(id_comprobante),
 id_nota_credito integer REFERENCES comprobantes(id_comprobante),
 id_usuario integer NOT NULL REFERENCES usuarios(id_usuario), fecha_creacion timestamptz NOT NULL,
 fecha_autorizacion timestamptz,
 CHECK((estado = 'Autorizado') = (cae IS NOT NULL))
);
-- Un número de AFIP corresponde a un único comprobante (los rechazados no consumen número).
CREATE UNIQUE INDEX IF NOT EXISTS ux_comprobantes_numero
 ON comprobantes(id_empresa, ambiente, punto_venta, tipo_comprobante, numero) WHERE estado <> 'Rechazado';
-- Una venta tiene a lo sumo una factura vigente (no anulada por nota de crédito).
CREATE UNIQUE INDEX IF NOT EXISTS ux_comprobantes_factura_venta
 ON comprobantes(id_venta) WHERE tipo_comprobante IN (1,6,11) AND estado <> 'Rechazado' AND id_nota_credito IS NULL;
CREATE INDEX IF NOT EXISTS ix_comprobantes_venta ON comprobantes(id_venta, id_comprobante DESC);
CREATE INDEX IF NOT EXISTS ix_comprobantes_sucursal ON comprobantes(id_empresa, id_sucursal, id_comprobante DESC);

-- Cliente al que se factura una venta (opcional; sin cliente es consumidor final).
ALTER TABLE ventas ADD COLUMN IF NOT EXISTS id_cliente integer REFERENCES clientes(id_cliente);

DO $$ BEGIN
 IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='foco_api') THEN
  GRANT SELECT,INSERT,UPDATE,DELETE ON afip_credenciales, afip_tokens TO foco_api;
  GRANT SELECT,INSERT,UPDATE ON comprobantes TO foco_api;
  REVOKE DELETE,TRUNCATE ON comprobantes FROM foco_api;
  GRANT USAGE,SELECT ON SEQUENCE comprobantes_id_comprobante_seq TO foco_api;
 END IF;
END $$;
COMMIT;
