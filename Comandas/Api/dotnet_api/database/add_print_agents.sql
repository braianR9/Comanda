-- Agente de impresión por sucursal: se conecta a la API con su clave (sin acceso a la base).
-- Ejecutar como propietario de las tablas.
BEGIN;
CREATE TABLE IF NOT EXISTS agentes_impresion (
    id_agente_impresion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa integer NOT NULL REFERENCES empresas(id_empresa),
    id_sucursal integer NOT NULL REFERENCES sucursales(id_sucursal),
    clave_hash varchar(64) NOT NULL UNIQUE,
    fecha_creacion timestamptz NOT NULL DEFAULT now(),
    ultimo_contacto timestamptz NULL,
    equipo varchar(150) NULL,
    CONSTRAINT uq_agentes_impresion_sucursal UNIQUE (id_empresa, id_sucursal)
);
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='foco_api') THEN
        GRANT SELECT,INSERT,UPDATE,DELETE ON agentes_impresion TO foco_api;
        GRANT USAGE,SELECT ON SEQUENCE agentes_impresion_id_agente_impresion_seq TO foco_api;
    END IF;
END $$;
COMMIT;
