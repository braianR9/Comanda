-- Ejecutar como propietario antes de desplegar. Conserva ventas y pagos originales.
BEGIN;
CREATE TABLE IF NOT EXISTS venta_anulaciones (
    id_venta integer PRIMARY KEY REFERENCES ventas(id_venta) ON DELETE RESTRICT,
    id_empresa integer NOT NULL REFERENCES empresas(id_empresa),
    id_sucursal integer NOT NULL REFERENCES sucursales(id_sucursal),
    id_caja integer NOT NULL REFERENCES cajas(id_caja),
    id_usuario integer NOT NULL REFERENCES usuarios(id_usuario),
    fecha timestamptz NOT NULL DEFAULT now(),
    motivo varchar(500) NOT NULL CHECK (length(trim(motivo)) >= 3),
    total_devuelto numeric(18,2) NOT NULL CHECK (total_devuelto >= 0)
);
CREATE INDEX IF NOT EXISTS ix_venta_anulaciones_fecha ON venta_anulaciones(id_empresa,id_sucursal,fecha DESC);
CREATE TABLE IF NOT EXISTS venta_devoluciones (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta integer NOT NULL REFERENCES venta_anulaciones(id_venta) ON DELETE RESTRICT,
    id_pago_original integer NOT NULL UNIQUE REFERENCES venta_pagos(id_pago) ON DELETE RESTRICT,
    medio_pago varchar(150) NOT NULL,
    importe numeric(18,2) NOT NULL CHECK (importe > 0)
);
CREATE INDEX IF NOT EXISTS ix_venta_devoluciones_venta ON venta_devoluciones(id_venta);
ALTER TABLE movimientos_stock DROP CONSTRAINT IF EXISTS movimientos_stock_origen_check;
ALTER TABLE movimientos_stock ADD CONSTRAINT movimientos_stock_origen_check
    CHECK (origen IN ('Manual','Venta','Compuesto','Compra','AnulacionVenta'));
CREATE UNIQUE INDEX IF NOT EXISTS ux_movimientos_stock_anulacion
    ON movimientos_stock(id_sucursal,id_producto,id_referencia) WHERE origen='AnulacionVenta';
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='foco_api') THEN
        GRANT SELECT,INSERT ON venta_anulaciones,venta_devoluciones TO foco_api;
        GRANT USAGE,SELECT ON SEQUENCE venta_devoluciones_id_seq TO foco_api;
    END IF;
END $$;
COMMIT;
