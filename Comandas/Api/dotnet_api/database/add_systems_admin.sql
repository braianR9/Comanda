-- Panel exclusivo de sistemas. No crea usuarios ni modifica empresas existentes.
BEGIN;
CREATE TABLE IF NOT EXISTS sistemas_eventos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha timestamptz NOT NULL DEFAULT now(),
    tipo varchar(20) NOT NULL,
    nivel varchar(20) NOT NULL,
    origen varchar(200) NOT NULL,
    mensaje text NOT NULL,
    detalle text,
    id_empresa integer,
    id_sucursal integer,
    id_usuario integer,
    metodo varchar(10),
    ruta varchar(500),
    estado_http integer,
    referencia varchar(100),
    resuelto boolean NOT NULL DEFAULT false,
    nota text
);
CREATE INDEX IF NOT EXISTS ix_sistemas_eventos_fecha ON sistemas_eventos(fecha DESC, id DESC);
CREATE INDEX IF NOT EXISTS ix_sistemas_eventos_filtros ON sistemas_eventos(tipo, resuelto, fecha DESC);
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'foco_api') THEN
        GRANT SELECT, INSERT ON sistemas_eventos TO foco_api;
        GRANT UPDATE (resuelto, nota) ON sistemas_eventos TO foco_api;
        GRANT USAGE, SELECT ON SEQUENCE sistemas_eventos_id_seq TO foco_api;
    END IF;
END $$;
COMMIT;
